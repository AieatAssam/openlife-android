package org.openlife.vault.crypto

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Test
import java.nio.charset.StandardCharsets
import java.util.HexFormat
import java.util.UUID
import javax.crypto.spec.SecretKeySpec

/**
 * Pins the exact wire bytes of a v1 envelope so an accidental change to the
 * binary layout (field order, byte order, length semantics) is caught even
 * if every unit test written against [EnvelopeCodec] and [AesGcmCodec]
 * directly still passes against itself. The fixture file was generated once
 * with a fixed key/nonce/plaintext/AAD (see the constants below) using the
 * JDK's own AES/GCM provider — the point is not to second-guess the JDK's
 * AES-GCM implementation, it is to freeze what OpenLife's framing produces
 * on disk. Design §10: "store an encoding fixture ... before integrating
 * UI."
 *
 * If this test ever needs to change, the fixture file must be regenerated
 * deliberately and the reason recorded in docs/decisions/ — a silent diff
 * here means the on-disk format changed, which breaks reading every
 * previously saved Source.
 */
class GoldenEnvelopeFixtureTest {

    private val key = SecretKeySpec(
        HexFormat.of().parseHex("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"),
        "AES",
    )
    private val plaintext = "OpenLife fixture plaintext for envelope tests".toByteArray(StandardCharsets.UTF_8)
    private val aad = EnvelopeAad.forDomain(EnvelopeDomain.ARTEFACT, version = 1)

    private fun readFixture(name: String = "golden-artefact-v1.hex"): ByteArray {
        val hex = requireNotNull(
            javaClass.getResourceAsStream("/envelope/$name"),
        ) { "golden fixture resource $name missing" }.bufferedReader().readText().trim()
        return HexFormat.of().parseHex(hex)
    }

    @Test
    fun goldenEnvelopeDecodesAndDecryptsToExpectedPlaintext() {
        val envelope = EnvelopeCodec.decode(readFixture())
        assertEquals(EnvelopeFormat.NONCE_LENGTH_BYTES, envelope.nonce.size)

        val decrypted = AesGcmCodec.decrypt(envelope, key, aad)
        assertArrayEquals(plaintext, decrypted)
    }

    @Test
    fun reEncodingTheDecodedGoldenEnvelopeReproducesTheSameBytes() {
        val original = readFixture()
        val envelope = EnvelopeCodec.decode(original)
        val reEncoded = EnvelopeCodec.encode(envelope)
        assertArrayEquals(original, reEncoded)
    }

    /**
     * P1-18-R7 (V-06): every artefact and wrapped DEK on disk is bound to its
     * Source UUID through [EnvelopeAad.forSource]. These two fixtures were
     * generated by scripts/fixtures/GenerateForSourceGoldenEnvelopes.java,
     * which builds the AAD by hand (version, label length, label, UUID most
     * then least significant bits, big-endian) and uses only the JDK's
     * AES/GCM. Any change to how the UUID is encoded into the AAD makes both
     * fail to authenticate here, even though every round-trip test would
     * still pass against itself.
     */
    @Test
    fun forSourceAadArtefactAndWrappedDekMatchCheckedInBytes() {
        val sourceId = UUID.fromString("0f1e2d3c-4b5a-6978-8796-a5b4c3d2e1f0")
        val wrappingKey = SecretKeySpec(
            HexFormat.of().parseHex("202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f"),
            "AES",
        )
        val expectedDek = HexFormat.of().parseHex("404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f")

        val wrappedDekBytes = readFixture("golden-wrapped-dek-forsource-v1.hex")
        val dek = AesGcmCodec.decrypt(
            EnvelopeCodec.decode(wrappedDekBytes),
            wrappingKey,
            EnvelopeAad.forSource(EnvelopeDomain.SOURCE_KEY, sourceId),
        )
        assertArrayEquals(expectedDek, dek)

        val artefactBytes = readFixture("golden-artefact-forsource-v1.hex")
        val artefact = AesGcmCodec.decrypt(
            EnvelopeCodec.decode(artefactBytes),
            SecretKeySpec(dek, "AES"),
            EnvelopeAad.forSource(EnvelopeDomain.ARTEFACT, sourceId),
        )
        assertArrayEquals("OpenLife forSource fixture plaintext".toByteArray(StandardCharsets.UTF_8), artefact)

        // The framing round-trips byte for byte, as for the forDomain fixture.
        assertArrayEquals(wrappedDekBytes, EnvelopeCodec.encode(EnvelopeCodec.decode(wrappedDekBytes)))
        assertArrayEquals(artefactBytes, EnvelopeCodec.encode(EnvelopeCodec.decode(artefactBytes)))
    }
}
